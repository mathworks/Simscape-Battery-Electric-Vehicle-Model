  methods (TestMethodSetup)
    % Functions in this "TestMethodSetup" section always run before
    % each test defined in the "Test" section runs.

    function test_method_setup_1(testcase)
      function closeAll
        close all
        bdclose all
      end  % nested function
      closeAll
      % addTeardown adds a function which always runs after each test.
      % Even if the execution of a test ends with an error, the teardown function runs.
      addTeardown(testcase, @closeAll)
    end  % function

  end  % methods

  methods (Test)
    % Functions in this "Test" section are the tests.
    % Before a function in this section runs, the TestSetup function
    % defined in the "TestMethodSetup" section runs.

    function test_BEV_Basic_generateMarkdown_1(testcase)
      % Check that all live scripts have been converted to markdown files.
      n = BEV_Basic_generateMarkdown;
      verifyEqual(testcase, n, 0)  % !test-target
    end  % function

  end  % methods

end  % classdef
